const {test,expect}=require('@playwright/test');
const snapshot=require('../assets/ro-suite/2.0.0/catalog.snapshot.json');
const endpoint='https://econds.github.io/ro_tools_portal/catalog/v1/tools.json';
const juno={id:'juno-festival-2026',title:'Juno Fall Academic Festival 2026',canonicalUrl:'https://econds.github.io/RO-Juno-Fall-Academic-Festival-2026/',listingStatus:'listed'};
for(const width of [320,390,1440]) test(`catalog, theme, keyboard, guide persistence at ${width}px`,async({page,context})=>{
 await page.setViewportSize({width,height:900});
 await context.grantPermissions(['clipboard-read','clipboard-write']);
 await page.route('https://**/*',r=>r.request().url()===endpoint?r.fulfill({contentType:'application/json',body:JSON.stringify({...snapshot,tools:[...snapshot.tools,juno]})}):r.abort());
 const requested=page.waitForRequest(endpoint);
 await page.goto('/');await requested;
 const host=page.locator('ro-suite-nav');
 await expect(host.locator('.current-text')).toHaveText(juno.title);
 const toggle=host.getByRole('button',{name:'เครื่องมืออื่น'});
 await expect(toggle).toHaveAttribute('aria-expanded','false');
 expect(await host.getByRole('navigation').evaluate(n=>getComputedStyle(n).backgroundColor)).toBe('rgb(31, 27, 39)');
 await toggle.click();await page.keyboard.press('Tab');
 await expect(host.getByRole('searchbox')).toBeFocused();
 await host.getByRole('searchbox').fill('Juno');
 await expect(host.locator('[aria-current="page"]')).toHaveAttribute('href',juno.canonicalUrl);
 await page.keyboard.press('Escape');await expect(toggle).toBeFocused();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 const box=page.locator('input[data-card]').first();await box.check();
 await expect(page.locator('#progText')).toHaveText('1 / 8 สี');
 await page.reload();await expect(box).toBeChecked();
 const cmd=page.locator('button.navi').first();const text=await cmd.getAttribute('data-cmd');
 await cmd.click();expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(text);
 await page.locator('#pDays').fill('14');await page.locator('#pTimes').fill('1');
 await expect(page.locator('#planOut .big')).toHaveText('7');
 await page.locator('#pDays').fill('6');await expect(page.locator('#planOut .warnline')).toBeVisible();
 await page.locator('#resetToday').click();await expect(page.locator('#progText')).toHaveText('0 / 8 สี');
 await page.reload();await expect(box).not.toBeChecked();
});
test('offline unknown identity and script failure keep guide usable',async({page})=>{
 await page.route('https://**/*',r=>r.abort());await page.goto('/');
 await expect(page.locator('ro-suite-nav .current-text')).toHaveText(juno.id);
 await page.locator('input[data-card]').first().check();
 await expect(page.locator('#progText')).toHaveText('1 / 8 สี');
 await page.route('**/2.0.0/nav.js',r=>r.abort());await page.reload();
 await expect(page.locator('ro-suite-nav > nav > a')).toBeVisible();
 await expect(page.locator('input[data-card]').first()).toBeChecked();
 await expect(page.locator('#planOut')).not.toBeEmpty();
});
